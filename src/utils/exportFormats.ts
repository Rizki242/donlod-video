import { jsPDF } from 'jspdf';
import { TranscriptSegment, VideoSummary, VideoMetadata } from '../types';

/**
 * Format seconds to SRT timestamp: HH:MM:SS,mmm
 */
export function formatSrtTime(totalSeconds: number): string {
  const hrs = Math.floor(totalSeconds / 3600);
  const mins = Math.floor((totalSeconds % 3600) / 60);
  const secs = Math.floor(totalSeconds % 60);
  const ms = Math.floor((totalSeconds % 1) * 1000);

  const pad = (n: number, z = 2) => n.toString().padStart(z, '0');
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(ms, 3)}`;
}

/**
 * Format seconds to WebVTT timestamp: HH:MM:SS.mmm
 */
export function formatVttTime(totalSeconds: number): string {
  const hrs = Math.floor(totalSeconds / 3600);
  const mins = Math.floor((totalSeconds % 3600) / 60);
  const secs = Math.floor(totalSeconds % 60);
  const ms = Math.floor((totalSeconds % 1) * 1000);

  const pad = (n: number, z = 2) => n.toString().padStart(z, '0');
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)}.${pad(ms, 3)}`;
}

/**
 * Generate standard SRT subtitle content
 */
export function generateSrt(segments: TranscriptSegment[]): string {
  return segments
    .map((seg, index) => {
      const start = formatSrtTime(seg.startSeconds);
      const end = formatSrtTime(seg.endSeconds > seg.startSeconds ? seg.endSeconds : seg.startSeconds + 3);
      const speakerPrefix = seg.speaker && seg.speaker !== 'Speaker' ? `[${seg.speaker}] ` : '';
      return `${index + 1}\n${start} --> ${end}\n${speakerPrefix}${seg.text}\n`;
    })
    .join('\n');
}

/**
 * Generate WebVTT subtitle content
 */
export function generateVtt(segments: TranscriptSegment[]): string {
  const body = segments
    .map((seg, index) => {
      const start = formatVttTime(seg.startSeconds);
      const end = formatVttTime(seg.endSeconds > seg.startSeconds ? seg.endSeconds : seg.startSeconds + 3);
      const speakerPrefix = seg.speaker && seg.speaker !== 'Speaker' ? `<v ${seg.speaker}>` : '';
      return `${index + 1}\n${start} --> ${end}\n${speakerPrefix}${seg.text}`;
    })
    .join('\n\n');

  return `WEBVTT - Generated by VideoScribe AI\n\n${body}`;
}

/**
 * Generate Markdown Document
 */
export function generateMarkdown(
  metadata: VideoMetadata,
  summary: VideoSummary | null,
  segments: TranscriptSegment[]
): string {
  let md = `# ${metadata.title}\n\n`;
  md += `> **Sumber**: ${metadata.author || 'Video'}\n`;
  if (metadata.url) md += `> **URL**: ${metadata.url}\n`;
  if (metadata.duration) md += `> **Durasi**: ${metadata.duration}\n`;
  md += `> **Tanggal Dibuat**: ${new Date().toLocaleDateString('id-ID', { dateStyle: 'full' })}\n\n`;

  if (summary) {
    md += `## 📌 Ringkasan Eksekutif\n\n${summary.executiveSummary}\n\n`;

    if (summary.keyTakeaways && summary.keyTakeaways.length > 0) {
      md += `## 💡 Poin-Poin Penting & Wawasan Kunci\n\n`;
      summary.keyTakeaways.forEach((item, i) => {
        md += `### ${i + 1}. ${item.point}\n`;
        md += `- **Kategori**: ${item.category}\n`;
        if (item.timestamp) md += `- **Waktu**: \`${item.timestamp}\`\n`;
        md += `${item.explanation}\n\n`;
      });
    }

    if (summary.chapters && summary.chapters.length > 0) {
      md += `## ⏱️ Pembagian Bab & Alur Waktu\n\n`;
      summary.chapters.forEach((ch) => {
        md += `- **[${ch.timestamp}]** **${ch.title}**: ${ch.summary}\n`;
      });
      md += `\n`;
    }

    if (summary.actionItems && summary.actionItems.length > 0) {
      md += `## ✅ Poin Tindakan / Rekomendasi Praktis\n\n`;
      summary.actionItems.forEach((act) => {
        md += `- [ ] ${act}\n`;
      });
      md += `\n`;
    }

    if (summary.faq && summary.faq.length > 0) {
      md += `## ❓ Tanya Jawab Kunci (FAQ)\n\n`;
      summary.faq.forEach((f) => {
        md += `**Q: ${f.question}**\n\n`;
        md += `A: ${f.answer}\n\n`;
      });
    }
  }

  md += `## 📝 Transkrip Lengkap Percakapan\n\n`;
  segments.forEach((seg) => {
    const speaker = seg.speaker ? `**${seg.speaker}** ` : '';
    md += `\`[${seg.start} - ${seg.end}]\` ${speaker}: ${seg.text}\n\n`;
  });

  return md;
}

/**
 * Generate Plain Text TXT
 */
export function generateTxt(
  metadata: VideoMetadata,
  summary: VideoSummary | null,
  segments: TranscriptSegment[]
): string {
  let txt = `=================================================================\n`;
  txt += `VIDEO SCRIBE AI - TRANSKRIP & RINGKASAN KONTEN\n`;
  txt += `Judul: ${metadata.title}\n`;
  txt += `Penerbit: ${metadata.author}\n`;
  if (metadata.url) txt += `URL: ${metadata.url}\n`;
  txt += `Tanggal: ${new Date().toLocaleString('id-ID')}\n`;
  txt += `=================================================================\n\n`;

  if (summary) {
    txt += `[ RINGKASAN EKSEKUTIF ]\n`;
    txt += `${summary.executiveSummary}\n\n`;

    if (summary.keyTakeaways?.length) {
      txt += `[ POIN-POIN PENTING ]\n`;
      summary.keyTakeaways.forEach((k, idx) => {
        txt += `${idx + 1}. ${k.point} (${k.category})\n   ${k.explanation}\n`;
      });
      txt += `\n`;
    }

    if (summary.chapters?.length) {
      txt += `[ ALUR BABAK / CHAPTER ]\n`;
      summary.chapters.forEach((ch) => {
        txt += `• [${ch.timestamp}] ${ch.title} - ${ch.summary}\n`;
      });
      txt += `\n`;
    }

    if (summary.actionItems?.length) {
      txt += `[ TINDAKAN / ACTION ITEMS ]\n`;
      summary.actionItems.forEach((act, idx) => {
        txt += `(${idx + 1}) ${act}\n`;
      });
      txt += `\n`;
    }
  }

  txt += `[ TRANSKRIP LENGKAP ]\n`;
  segments.forEach((s) => {
    txt += `[${s.start}] ${s.speaker ? s.speaker + ': ' : ''}${s.text}\n`;
  });

  return txt;
}

/**
 * Generate structured JSON
 */
export function generateJson(
  metadata: VideoMetadata,
  summary: VideoSummary | null,
  segments: TranscriptSegment[]
): string {
  return JSON.stringify(
    {
      metadata: {
        title: metadata.title,
        author: metadata.author,
        url: metadata.url || null,
        duration: metadata.duration || null,
        exportDate: new Date().toISOString(),
      },
      summary: summary || null,
      transcript: segments,
    },
    null,
    2
  );
}

/**
 * Generate PDF Document using jsPDF
 */
export function generatePdf(
  metadata: VideoMetadata,
  summary: VideoSummary | null,
  segments: TranscriptSegment[]
): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - margin) {
      doc.addPage();
      y = margin;
      return true;
    }
    return false;
  };

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.roundedRect(margin, y, contentWidth, 22, 3, 3, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('VideoScribe AI - Laporan Ringkasan & Transkrip', margin + 6, y + 9);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text(`Dihasilkan pada: ${new Date().toLocaleDateString('id-ID', { dateStyle: 'medium' })} | Durasi hingga 180 Menit`, margin + 6, y + 16);

  y += 28;

  // Title
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  const titleLines = doc.splitTextToSize(metadata.title, contentWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 7 + 2;

  // Metadata subtext
  doc.setFontSize(9);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(100, 116, 139);
  doc.text(`Kreator: ${metadata.author || 'Tidak diketahui'} ${metadata.url ? `| URL: ${metadata.url.slice(0, 50)}...` : ''}`, margin, y);
  y += 8;

  // Divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  if (summary) {
    // Executive Summary
    checkPageBreak(30);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30, 41, 59);
    doc.text('1. Ringkasan Eksekutif', margin, y);
    y += 6;

    // Summary Box
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(203, 213, 225);
    doc.setFontSize(9.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);

    const summaryLines = doc.splitTextToSize(summary.executiveSummary, contentWidth - 8);
    const boxHeight = summaryLines.length * 4.8 + 6;
    checkPageBreak(boxHeight);

    doc.roundedRect(margin, y, contentWidth, boxHeight, 2, 2, 'FD');
    doc.text(summaryLines, margin + 4, y + 5);
    y += boxHeight + 8;

    // Key Takeaways
    if (summary.keyTakeaways && summary.keyTakeaways.length > 0) {
      checkPageBreak(25);
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(30, 41, 59);
      doc.text('2. Poin-Poin Penting & Wawasan Kunci', margin, y);
      y += 6;

      summary.keyTakeaways.forEach((item, idx) => {
        checkPageBreak(18);
        doc.setFontSize(10);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(15, 23, 42);
        doc.text(`• ${idx + 1}. ${item.point}`, margin + 2, y);
        y += 4.5;

        doc.setFontSize(8.5);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(71, 85, 105);
        const explLines = doc.splitTextToSize(`[${item.category}] ${item.explanation}`, contentWidth - 8);
        doc.text(explLines, margin + 6, y);
        y += explLines.length * 4 + 3;
      });
      y += 4;
    }

    // Chapters
    if (summary.chapters && summary.chapters.length > 0) {
      checkPageBreak(25);
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(30, 41, 59);
      doc.text('3. Alur Babak Video (Timeline)', margin, y);
      y += 6;

      summary.chapters.forEach((ch) => {
        checkPageBreak(12);
        doc.setFontSize(9);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(79, 70, 229); // indigo-600
        doc.text(`[${ch.timestamp}]`, margin + 2, y);

        doc.setFont('helvetica', 'bold');
        doc.setTextColor(15, 23, 42);
        doc.text(ch.title, margin + 20, y);
        y += 4.5;

        doc.setFont('helvetica', 'normal');
        doc.setTextColor(71, 85, 105);
        const chSummaryLines = doc.splitTextToSize(ch.summary, contentWidth - 22);
        doc.text(chSummaryLines, margin + 20, y);
        y += chSummaryLines.length * 4 + 2;
      });
      y += 5;
    }

    // Action Items
    if (summary.actionItems && summary.actionItems.length > 0) {
      checkPageBreak(20);
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(30, 41, 59);
      doc.text('4. Poin Aksi & Rekomendasi Praktis', margin, y);
      y += 6;

      summary.actionItems.forEach((act) => {
        checkPageBreak(10);
        doc.setFontSize(9);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(51, 65, 85);
        const actLines = doc.splitTextToSize(`✔ ${act}`, contentWidth - 4);
        doc.text(actLines, margin + 2, y);
        y += actLines.length * 4.2 + 1.5;
      });
      y += 5;
    }
  }

  // Full Transcript Section
  checkPageBreak(30);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('5. Transkrip Percakapan Lengkap', margin, y);
  y += 6;

  segments.forEach((seg) => {
    checkPageBreak(12);
    doc.setFontSize(8);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(99, 102, 241); // indigo
    doc.text(`[${seg.start}]`, margin, y);

    if (seg.speaker) {
      doc.setTextColor(71, 85, 105);
      doc.text(`${seg.speaker}:`, margin + 18, y);
    }

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(15, 23, 42);
    const textLines = doc.splitTextToSize(seg.text, contentWidth - 40);
    doc.text(textLines, margin + 38, y);
    y += Math.max(textLines.length * 3.8, 5) + 1.5;
  });

  // Footer on each page
  const pageCount = (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Halaman ${i} dari ${pageCount} — VideoScribe AI`,
      pageWidth / 2,
      pageHeight - 8,
      { align: 'center' }
    );
  }

  const cleanFilename = metadata.title.replace(/[^a-zA-Z0-9_\-]/g, '_').slice(0, 40);
  doc.save(`${cleanFilename}_Ringkasan_Transkrip.pdf`);
}

/**
 * Triggers browser download for any text or blob content
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
